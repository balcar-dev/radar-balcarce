/** Cuántas hay de cada clase, para el resumen. */
export function resumenFondo(lista = BALCARCE_FONDO) {
  const porComo = Object.fromEntries(Object.keys(COMO).map((k) => [k, lista.filter((f) => f.como === k).length]));
  return {
    total: lista.length,
    enUso: lista.filter((f) => f.registroIds.length).length,
    nuevas: lista.filter((f) => f.nueva).length,
    porComo,
    sumar: lista.filter((f) => f.accion === 'sumar').length,
  };
}
